#!/usr/bin/env python3
"""Rebuild the checked-in Vulkan 1.0 shader from its complete GLSL source."""
import argparse
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--compiler', default='glslangValidator')
parser.add_argument('--validator', default='spirv-val')
parser.add_argument('--check', action='store_true', help='verify without replacing the embedded module')
args = parser.parse_args()
root = Path(__file__).resolve().parent.parent
source = root / 'shaders/orbit.comp'
destination = root / 'src/generated/orbit_spv.hpp'
with tempfile.TemporaryDirectory(prefix='apophysis-shader-') as directory:
    output = Path(directory) / 'orbit.spv'
    subprocess.run([args.compiler, '-V', '--target-env', 'vulkan1.0', str(source), '-o', str(output)], check=True)
    subprocess.run([args.validator, '--target-env', 'vulkan1.0', str(output)], check=True)
    data = output.read_bytes()
words = struct.unpack('<' + 'I' * (len(data) // 4), data)
header = ('// Generated by scripts/compile_shader.py; do not edit.\n'
          '// GLSL SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
          '// SPIR-V SHA-256: ' + hashlib.sha256(data).hexdigest() + '\n'
          '#pragma once\n#include <cstdint>\nnamespace apo::gpu {\n'
          'inline constexpr std::uint32_t orbit_spv[] = {\n')
header += ''.join('    ' + ', '.join(f'0x{v:08x}u' for v in words[i:i+8]) + ',\n'
                  for i in range(0, len(words), 8))
header += '};\n}\n'
if args.check:
    if not destination.is_file() or destination.read_text() != header:
        raise SystemExit('Embedded shader differs; regenerate with the pinned compiler and review the change.')
    print('Embedded shader matches validated GLSL compilation.')
else:
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(header)
    print(f'Embedded {len(data)} validated SPIR-V bytes in {destination.relative_to(root)}')
